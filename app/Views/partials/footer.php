function drawLhWheel() {
    const canvas = document.getElementById('lhWheelCanvas');
    if (!canvas) return;
    const ctx = canvas.getContext('2d');
    const numSegs = wheelSegments.length;
    const angle = 2 * Math.PI / numSegs;
    const radius = canvas.width / 2;
    
    ctx.clearRect(0, 0, canvas.width, canvas.height);
    
    wheelSegments.forEach((seg, i) => {
        const startAngle = i * angle;
        const endAngle = startAngle + angle;
        
        ctx.beginPath();
        ctx.moveTo(radius, radius);
        ctx.arc(radius, radius, radius, startAngle, endAngle);
        ctx.closePath();
        
        ctx.fillStyle = seg.color;
        ctx.fill();
        
        // Draw divider
        ctx.lineWidth = 1.5;
        ctx.strokeStyle = '#3e2723';
        ctx.stroke();
        
        ctx.save();
        ctx.translate(radius, radius);
        ctx.rotate(startAngle + angle / 2);
        
        ctx.fillStyle = '#3e2723';
        ctx.font = 'bold 12px sans-serif';
        ctx.textAlign = 'right';
        ctx.fillText(seg.label, radius - 20, 5);
        ctx.restore();
    });
    
    // Draw center pin
    ctx.beginPath();
    ctx.arc(radius, radius, 12, 0, 2 * Math.PI);
    ctx.fillStyle = '#3e2723';
    ctx.fill();
    ctx.beginPath();
    ctx.arc(radius, radius, 6, 0, 2 * Math.PI);
    ctx.fillStyle = '#ebdcc6';
    ctx.fill();
}

